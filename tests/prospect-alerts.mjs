import assert from 'node:assert/strict';
import fs from 'node:fs';

const source=fs.readFileSync('prospectAlerts.js','utf8');
const {buildUnscheduledProspectsAlert}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.equal(buildUnscheduledProspectsAlert(0),null);
assert.equal(buildUnscheduledProspectsAlert(null),null);
console.log('PASS no false alert without missing follow-ups');
const one=buildUnscheduledProspectsAlert(1);
assert.equal(one.title,'1 prospecto sin próxima acción');
assert.equal(one.page,'pipeline');
assert.equal(one.tone,'watch');
console.log('PASS one missing follow-up opens CRM pipeline');
const thirty=buildUnscheduledProspectsAlert(30);
assert.equal(thirty.title,'30 prospectos sin próxima acción');
assert.equal(thirty.key,one.key,'Same alert key prevents bell flooding');
assert.notEqual(thirty.version,one.version,'Changing total should refresh read status');
assert.equal(thirty.date,null);
console.log('PASS 30 missing follow-ups generate one compact, revisitable alert');
const app=fs.readFileSync('app.js','utf8');
assert.ok(app.includes('buildUnscheduledProspectsAlert(unscheduledCount)'));
assert.ok(app.includes('count:"exact",head:true'));
assert.ok(app.includes('.is("next_action_at",null)'));
assert.ok(app.includes('.is("archived_at",null)'));
assert.ok(app.includes('.filter((row)=>Boolean(row.next_action_at))'));
console.log('PASS dashboard obtains server-side aggregate, excludes archived and avoids per-lead duplicate bell alerts');
const html=fs.readFileSync('index.html','utf8');
assert.ok(html.includes('app.js?v=20261016-ready1'));
console.log('PASS dashboard reloads updated app code');
console.log('PROSPECT ALERTS: 5/5 checks passed; no CRM records modified.');
